
#!/usr/bin/env bash

set -Eeuo pipefail

# Resolve the repository directory from this script's location.
ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
SOURCE_DIR="$ROOT_DIR/sources"
OUTPUT_FILE="$ROOT_DIR/AGENTS.md"
CODEX_DIR="$HOME/.codex"
GLOBAL_FILE="$CODEX_DIR/AGENTS.md"

# List the Markdown files that should be loaded as global instructions.
# Reference templates, examples, and explanations are intentionally excluded.
SOURCE_FILES=(
    "$SOURCE_DIR/01-core/01-personal-rules.md"
    "$SOURCE_DIR/01-core/02-task-workflow.md"
    "$SOURCE_DIR/02-coding/01-coding-patterns.md"
)

# Fail early if a required instruction file is missing.
for file in "${SOURCE_FILES[@]}"; do
    if [[ ! -f "$file" ]]; then
        printf 'Error: required instruction file not found: %s\n' \
            "$file" >&2
        exit 1
    fi
done


# Build the combined instructions in a temporary file first.
TEMP_FILE="$(mktemp "$ROOT_DIR/.AGENTS.md.XXXXXX")"
trap 'rm -f -- "$TEMP_FILE" "${INSTALL_TEMP:-}"' EXIT

{
    printf '# Global Codex Instructions\n\n'
    printf '> Generated by build-agents.sh. Edit the source files under sources/, not this file.\n\n'

    for file in "${SOURCE_FILES[@]}"; do
        relative_path="${file#"$SOURCE_DIR"/}"

        printf '\n---\n\n'
        printf '<!-- Source: %s -->\n\n' "$relative_path"
        printf '# Source: %s\n\n' "$relative_path"
        cat -- "$file"
        printf '\n'
    done
} > "$TEMP_FILE"

# Keep a reviewable copy in the repository.
cp -- "$TEMP_FILE" "$OUTPUT_FILE"

# Prepare the global Codex directory.
mkdir -p -- "$CODEX_DIR"

# Back up existing global instructions before replacing them.
if [[ -f "$GLOBAL_FILE" ]]; then
    BACKUP_FILE="$GLOBAL_FILE.bak.$(date +%Y%m%d-%H%M%S)"
    cp -p -- "$GLOBAL_FILE" "$BACKUP_FILE"
    printf 'Backup created: %s\n' "$BACKUP_FILE"
fi

# Install atomically so Codex never sees a partially written file.
INSTALL_TEMP="$(mktemp "$CODEX_DIR/.AGENTS.md.XXXXXX")"
cp -- "$TEMP_FILE" "$INSTALL_TEMP"
chmod 600 "$INSTALL_TEMP"
mv -f -- "$INSTALL_TEMP" "$GLOBAL_FILE"
INSTALL_TEMP=""

printf '\nSuccessfully built and installed global Codex instructions.\n'
printf 'Source files: %s\n' "${#SOURCE_FILES[@]}"
printf 'Repository copy: %s\n' "$OUTPUT_FILE"
printf 'Global instructions: %s\n' "$GLOBAL_FILE"